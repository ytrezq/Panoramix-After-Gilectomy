#!/usr/bin/env python3
"""
The automaton of spec/evm_decoder.rl as tables for src/decoder.s: runs
`ragel -x` on it (or reads its XML) and writes

- src/evm_dfa.s: dfa_states (for each state: the index of its first
  transition, the mask of a byte - 0 where one transition is for every
  byte, 0xff where each byte has its own), dfa_trans (the next state, and
  where its actions are in dfa_programs), dfa_programs (the actions of the
  transitions, DA_* codes, 0 at the end), dfa_action_names;
- include/evm_dfa.inc: the DA_* codes of the actions, DFA_START, DFA_STATES.

    tools/rl2asm.py [--xml FILE] [OUT]

(OUT: where src/ and include/ are written, the repository by default -
make dfa-check writes them into build/dfa_check to compare)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import dfa_xml  # noqa: E402

ROOT = os.path.join(HERE, "..")
args = sys.argv[1:]
xml = None
if args[:1] == ["--xml"]:
    xml = args[1]
    args = args[2:]
OUT = args[0] if args else ROOT


def tables(dfa):
    ids = sorted(dfa.states)
    assert ids == list(range(len(ids))), "the states aren't numbered from 0"
    assert len(ids) < 1 << 16
    programs = [0]              # (0: no actions)
    program_of = {(): 0}
    states, trans = [], []
    for sid in ids:
        row = [dfa.step(sid, b) for b in range(256)]
        assert None not in row, f"state {sid} has no transition for a byte: the decoder would stop"
        for target, acts in row:
            if acts not in program_of:
                program_of[acts] = len(programs)
                programs += [a + 1 for a in acts] + [0]
        uniform = all(r == row[0] for r in row)
        states.append((len(trans), 0 if uniform else 0xFF))
        trans += [(t, program_of[a]) for t, a in (row[:1] if uniform else row)]
    assert len(programs) < 1 << 16
    return states, trans, programs


def write(path, text):
    path = os.path.join(OUT, path)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def main():
    dfa = dfa_xml.load(xml) if xml else dfa_xml.run_ragel(ROOT)
    states, trans, programs = tables(dfa)
    head = "# generated by tools/rl2asm.py from spec/evm_decoder.rl - do not edit\n"
    inc = [head, "# the actions of the decoder's automaton (dfa_programs' codes)"]
    for aid, name in sorted(dfa.actions.items()):
        inc.append(f".set DA_{name.upper()}, {aid + 1}")
    inc += [
        "",
        f".set DFA_START, {dfa.start}           # the state it starts in",
        f".set DFA_STATES, {len(states)}",
        "",
    ]
    out = [
        head,
        '.include "evm_dfa.inc"',
        "",
        "# for each state: the index of its first transition (u32), the mask of a",
        "# byte (u8: 0, one transition for every byte; 0xff, one for each), 0",
        "        .section .rodata",
        "        .align 8",
        "        .globl dfa_states, dfa_trans, dfa_programs",
        "        .hidden dfa_states, dfa_trans, dfa_programs",
        "dfa_states:",
    ]
    for i in range(0, len(states), 4):
        out.append("        .quad " + ", ".join(f"0x{m << 32 | b:x}" for b, m in states[i : i + 4]))
    out += [
        "",
        "# for each transition: the next state (u16), the index of its actions in",
        "# dfa_programs (u16, 0: none)",
        "        .align 4",
        "dfa_trans:",
    ]
    for i in range(0, len(trans), 8):
        out.append("        .long " + ", ".join(f"0x{p << 16 | t:x}" for t, p in trans[i : i + 8]))
    out += [
        "",
        "# the actions of the transitions: DA_* codes, in the order they're run,",
        "# 0 at the end",
        "dfa_programs:",
    ]
    for i in range(0, len(programs), 16):
        out.append("        .byte " + ", ".join(str(p) for p in programs[i : i + 16]))
    out += [
        "",
        "# the names of the actions, by DA_* code",
        "        .section .data.rel.ro",
        "        .align 8",
        "        .globl dfa_action_names",
        "        .hidden dfa_action_names",
        "dfa_action_names:",
        "        .quad 0",
    ]
    out += [f"        .quad .Lda_{aid + 1}" for aid in sorted(dfa.actions)]
    out.append("        .section .rodata")
    out += [f'.Lda_{aid + 1}: .asciz "{name}"' for aid, name in sorted(dfa.actions.items())]
    out += ["", '        .section .note.GNU-stack,"",@progbits', ""]
    write("include/evm_dfa.inc", "\n".join(inc))
    write("src/evm_dfa.s", "\n".join(out))
    print(f"{len(states)} states, {len(trans)} transitions in the tables, {len(programs)} bytes of actions")


if __name__ == "__main__":
    main()
