#!/usr/bin/env python3
"""
From spec/evm.def, the instructions of the EVM:

- spec/evm_insns.rl: a ragel machine for each instruction (its opcode, then
  its immediate's bytes), `unknown` for the bytes that aren't an opcode,
  `instruction` for all of them - what spec/evm_decoder.rl is made of (as
  NaCl's validator is of the machines gen_dfa makes from its .def files);
- src/evm_ops.s: what the decoder reads of an opcode when an instruction
  ends - its kind, its immediate's size, a dup's or a swap's n - and the
  names the disassembly prints; include/evm_ops.inc, the kinds (EK_*).

    tools/gen_dfa.py [ROOT]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import evm_spec  # noqa: E402

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..")

# the kinds of instructions (src/evm_ops.s: evm_opinfo's low byte; defs.inc)
KIND_UNKNOWN, KIND_PLAIN, KIND_PUSH, KIND_DUPSWAP, KIND_JUMPDEST = range(5)


def kind(op):
    if op is None:
        return KIND_UNKNOWN
    if op.name.startswith("push"):
        return KIND_PUSH
    if "dup" in op.flags or "swap" in op.flags:
        return KIND_DUPSWAP
    if "jumpdest" in op.flags:
        return KIND_JUMPDEST
    return KIND_PLAIN


def dupswap_n(op):
    if op is None or kind(op) != KIND_DUPSWAP:
        return 0
    return int(op.name[4 if op.name.startswith("swap") else 3 :])


def ranges(codes):
    """[(lo, hi)] of a sorted list of bytes"""
    res = []
    for c in codes:
        if res and res[-1][1] == c - 1:
            res[-1] = (res[-1][0], c)
        else:
            res.append((c, c))
    return res


def rl(ops):
    out = [
        "// generated by tools/gen_dfa.py from spec/evm.def - do not edit",
        "%%{",
        "  machine evm_insns;",
        "",
        "  # an instruction: its opcode, then its immediate's bytes",
    ]
    for code, op in sorted(ops.items()):
        imm = f" any{{{op.imm}}}" if op.imm > 1 else " any" if op.imm == 1 else ""
        out.append(f"  op_{op.name} = 0x{code:02x}{imm};")
    unknown = [b for b in range(256) if b not in ops]
    alts = " | ".join(f"0x{lo:02x}" if lo == hi else f"0x{lo:02x}..0x{hi:02x}" for lo, hi in ranges(unknown))
    out += [
        "",
        "  # the bytes that aren't an opcode: an instruction of a byte",
        f"  unknown = {alts};",
        "",
        "  # any instruction",
        "  instruction = " + "\n    | ".join(f"op_{op.name}" for _, op in sorted(ops.items())) + "\n    | unknown;",
        "",
        "  # the pushes",
        "  push_any = " + " | ".join(f"op_{op.name}" for _, op in sorted(ops.items()) if kind(op) == KIND_PUSH) + ";",
        "}%%",
        "",
    ]
    return "\n".join(out)


def asm(ops):
    out = [
        "# generated by tools/gen_dfa.py from spec/evm.def - do not edit",
        "",
        "# evm_opinfo: for each byte, what the decoder reads of the instruction",
        "# it opens when an instruction ends - its kind (EK_*, evm_ops.inc), the",
        "# size of its immediate, a dup's or a swap's n",
        "#",
        "#   kind | imm << 8 | n << 16",
        "#",
        "# evm_opnames: its name (NULL: python's UNKNOWN)",
        "",
        "        .section .rodata",
        "        .align 4",
        "        .globl evm_opinfo",
        "        .hidden evm_opinfo",
        "evm_opinfo:",
    ]
    for row in range(0, 256, 8):
        vals = []
        for b in range(row, row + 8):
            op = ops.get(b)
            vals.append(f"0x{kind(op) | (op.imm if op else 0) << 8 | dupswap_n(op) << 16:06x}")
        out.append("        .long " + ", ".join(vals))
    out += [
        "",
        "        .section .data.rel.ro",
        "        .align 8",
        "        .globl evm_opnames",
        "        .hidden evm_opnames",
        "evm_opnames:",
    ]
    for row in range(0, 256, 8):
        out.append("        .quad " + ", ".join(f".Lop_{b:02x}" if b in ops else "0" for b in range(row, row + 8)))
    out += ["", "        .section .rodata"]
    for code, op in sorted(ops.items()):
        out.append(f".Lop_{code:02x}: .asciz \"{op.name}\"")
    out += ["", '        .section .note.GNU-stack,"",@progbits', ""]
    return "\n".join(out)


def write(path, text):
    path = os.path.join(ROOT, path)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def inc():
    return "\n".join([
        "# generated by tools/gen_dfa.py from spec/evm.def - do not edit",
        "",
        "# the kinds of instructions (evm_opinfo's low byte)",
        f".set EK_UNKNOWN, {KIND_UNKNOWN}           # a byte that isn't an opcode: python's UNKNOWN",
        f".set EK_PLAIN, {KIND_PLAIN}",
        f".set EK_PUSH, {KIND_PUSH}              # its parameter: its immediate",
        f".set EK_DUPSWAP, {KIND_DUPSWAP}           # its parameter: n",
        f".set EK_JUMPDEST, {KIND_JUMPDEST}",
        "",
    ])


if __name__ == "__main__":
    ops = evm_spec.read_def()
    write("spec/evm_insns.rl", rl(ops))
    write("src/evm_ops.s", asm(ops))
    write("include/evm_ops.inc", inc())
