std::string hex(const sha256::Digest& d)
{
    static constexpr char digits[] = "0123456789abcdef";
    std::string s;
    for (std::uint8_t b : d) {
        s += digits[b >> 4];
        s += digits[b & 15];
    }
    return s;
}

std::vector<sha256::Impl> impls_here()
{
    std::vector<sha256::Impl> res;
    for (sha256::Impl impl : sha256::all_impls) {
        if (sha256::supported(impl))
            res.push_back(impl);
        else
            MESSAGE("sha256: no ", sha256::name(impl), " on this processor: not tested");
    }
    return res;
}

