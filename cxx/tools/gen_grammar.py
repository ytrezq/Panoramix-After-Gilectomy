#!/usr/bin/env python3
"""Generate the EVM decoder's grammar from spec/evm.def (NaCl's gen_dfa.py).

    gen_grammar.py --evm ../spec/evm.def -o $(B)/gen/src/evm/evm_grammar.rlh

Writes the Ragel machine `evm_grammar`, which the decoder's machines include
(`include evm_grammar "evm/evm_grammar.rlh";`, after `alphtype unsigned char;`
and the definitions of the actions it names):

  insn        one instruction: an alternative per opcode - the opcode, then
              the n bytes of its immediate (a PUSHn's), each with $imm_byte;
              on its last byte the action of its class:
                insn_plain insn_push insn_dup insn_swap insn_jump insn_jumpi
                insn_jumpdest insn_halt insn_unknown
              (a byte that isn't an opcode: a one-byte instruction, unknown)
  op_<name>   the bare bytes of each opcode (no actions), op_unknown, and
              push_any (PUSH0..PUSH32): what the idioms are made of

The class of an opcode comes from evm.def's flags (dup, swap, jumpdest; jump:
JUMP if it takes 1 word, JUMPI if 2; halt), else push for the pushes (their
names), else plain - core's kClass (tools/gen_ops.py) must agree, which
tests/evm_*_test.cpp checks.

Fails (exit 1) on a malformed evm.def line, a duplicate opcode or name, an
unknown flag, an immediate on anything but a push. The output is deterministic.
"""
import argparse
import os
import sys

CLASSES = ["plain", "push", "dup", "swap", "jump", "jumpi", "jumpdest", "halt", "unknown"]
FLAGS = {"halt", "jump", "jumpdest", "dup", "swap"}


class SpecError(Exception):
    pass


def read_def(path):
    """{opcode: (name, imm, pops, pushes, flags)} of evm.def"""
    ops, names = {}, set()
    with open(path, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            w = line.split("#", 1)[0].split()
            if not w:
                continue
            if len(w) < 6:
                raise SpecError(f"{path}:{n}: expected: opcode name imm in out since [flags]")
            try:
                code, imm, pops, pushes = int(w[0], 16), int(w[2]), int(w[3]), int(w[4])
            except ValueError:
                raise SpecError(f"{path}:{n}: bad number") from None
            name, flags = w[1], frozenset(w[6:])
            if not 0 <= code < 256:
                raise SpecError(f"{path}:{n}: opcode {w[0]} out of a byte")
            if code in ops or name in names:
                raise SpecError(f"{path}:{n}: duplicate opcode or name")
            if flags - FLAGS:
                raise SpecError(f"{path}:{n}: unknown flag {sorted(flags - FLAGS)[0]}")
            if not name.replace("_", "").isalnum():
                raise SpecError(f"{path}:{n}: bad name {name!r}")
            if imm and not name.startswith("push") or not 0 <= imm <= 32:
                raise SpecError(f"{path}:{n}: an immediate of {imm} bytes on {name}")
            ops[code] = (name, imm, pops, pushes, flags)
            names.add(name)
    return ops


def klass(name, imm, pops, flags):
    """the class of an opcode (the same rules as gen_ops.py's evm_class)"""
    if "dup" in flags:
        return "dup"
    if "swap" in flags:
        return "swap"
    if "jumpdest" in flags:
        return "jumpdest"
    if "jump" in flags:
        return "jump" if pops == 1 else "jumpi"
    if "halt" in flags:
        return "halt"
    if imm > 0 or name.startswith("push"):
        return "push"
    return "plain"


def byte_union(codes):
    """the bytes as a Ragel union of ranges"""
    runs = []
    for c in sorted(codes):
        if runs and runs[-1][1] == c - 1:
            runs[-1][1] = c
        else:
            runs.append([c, c])
    return " | ".join(f"0x{lo:02x}" if lo == hi else f"0x{lo:02x}..0x{hi:02x}" for lo, hi in runs)


def generate(ops):
    unknown = [b for b in range(256) if b not in ops]
    out = []
    p = out.append
    p("// GENERATED by cxx/tools/gen_grammar.py from spec/evm.def - do not edit.")
    p("// The EVM decoder's grammar: cxx/src/evm/decoder.hpp says how to use it.")
    p("%%{")
    p("  machine evm_grammar;")
    p("")
    p("  # the bare bytes of each opcode (no actions): the idioms' building blocks")
    for code, (name, imm, _pops, _pushes, _flags) in sorted(ops.items()):
        body = f"0x{code:02x}" + (f" any{{{imm}}}" if imm else "")
        p(f"  op_{name} = {body};")
    p(f"  op_unknown = {byte_union(unknown)};")
    pushes = [name for _c, (name, imm, pops, _o, flags) in sorted(ops.items()) if klass(name, imm, pops, flags) == "push"]
    p("  push_any = " + " | ".join(f"op_{n}" for n in pushes) + ";")
    p("")
    p("  # one instruction: the opcode, its immediate's bytes ($imm_byte), the")
    p("  # action of its class on its last byte")
    alts = []
    for code, (name, imm, pops, _pushes, flags) in sorted(ops.items()):
        k = klass(name, imm, pops, flags)
        body = f"0x{code:02x}" + (f" (any{{{imm}}} $imm_byte)" if imm else "")
        alts.append(f"{body} @insn_{k}".ljust(40) + f"# {name}")
    alts.append(f"({byte_union(unknown)}) @insn_unknown")
    p("  insn =")
    p("      " + alts[0])
    for a in alts[1:]:
        p("    | " + a)
    p("    ;")
    p("}%%")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--evm", required=True)
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args(argv)
    try:
        text = generate(read_def(a.evm))
    except (SpecError, OSError) as e:
        print(f"gen_grammar.py: error: {e}", file=sys.stderr)
        return 1
    d = os.path.dirname(a.out)
    if d:
        os.makedirs(d, exist_ok=True)
    tmp = a.out + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
